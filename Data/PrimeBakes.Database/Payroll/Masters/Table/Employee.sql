CREATE TABLE [dbo].[Employee]
(
	[Id] INT NOT NULL PRIMARY KEY IDENTITY, 
    [Name] VARCHAR(500) NOT NULL UNIQUE, 
    [Code] VARCHAR(10) NOT NULL UNIQUE, 
    [LocationId] INT NOT NULL, 
    [DepartmentId] INT NOT NULL, 
    [DesignationId] INT NOT NULL, 
    [UserId] INT NULL, 
    [DateOfJoining] DATE NOT NULL, 
    [DateOfLeaving] DATE NULL, 
    [DateOfBirth] DATE NULL, 
    [Gender] VARCHAR(10) NULL, 
    [FatherOrHusbandName] VARCHAR(500) NULL, 
    [Phone] VARCHAR(20) NULL, 
    [Email] VARCHAR(250) NULL, 
    [Address] VARCHAR(MAX) NULL, 
    [PAN] VARCHAR(10) NULL, 
    [Aadhaar] VARCHAR(12) NULL, 
    [PFNumber] VARCHAR(50) NULL, 
    [UANNumber] VARCHAR(20) NULL, 
    [ESINumber] VARCHAR(50) NULL, 
    [BankName] VARCHAR(250) NULL, 
    [BankAccountNumber] VARCHAR(50) NULL, 
    [IFSC] VARCHAR(11) NULL, 
    [PaymentMode] VARCHAR(20) NULL, 
    [Remarks] VARCHAR(MAX) NULL,
    [Status] BIT NOT NULL DEFAULT 1, 
    CONSTRAINT [FK_Employee_ToLocation] FOREIGN KEY ([LocationId]) REFERENCES [Location](Id), 
    CONSTRAINT [FK_Employee_ToDepartment] FOREIGN KEY ([DepartmentId]) REFERENCES [Department](Id), 
    CONSTRAINT [FK_Employee_ToDesignation] FOREIGN KEY ([DesignationId]) REFERENCES [Designation](Id), 
    CONSTRAINT [FK_Employee_ToUser] FOREIGN KEY ([UserId]) REFERENCES [User](Id)
)
